@dataclass(frozen=True, slots=True)
class OfferComparison:
    offers: list[dict]
    best_compensation: str | None
    earliest_start: str | None
    fewest_conditions: int


def compare_offers(offers: list[dict]) -> OfferComparison:
    """Compare multiple offers side by side."""
    if not offers:
        return OfferComparison([], None, None, 0)
    best_comp = max(offers, key=lambda o: len(o.get("compensation_text", "")))
    earliest = min(offers, key=lambda o: o.get("start_date", "9999"))
    fewest = min(len(o.get("conditions", [])) for o in offers)
    return OfferComparison(
        offers=offers,
        best_compensation=best_comp.get("role_title"),
        earliest_start=earliest.get("start_date"),
        fewest_conditions=fewest,
    )


