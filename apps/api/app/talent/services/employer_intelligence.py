# Gap #109: Offer deadline reminder
# ---------------------------------------------------------------------------

def compute_offer_deadline_alerts(offers: list[dict], days_ahead: int = 3) -> list[dict]:
    """Find offers expiring within N days."""
    now = datetime.now(UTC)
    alerts = []
    for o in offers:
        exp = o.get("expires_at")
        if not exp:
            continue
        if isinstance(exp, str):
            try:
                from datetime import datetime as dt
                exp = dt.fromisoformat(exp)
            except (ValueError, TypeError):
                continue
        from datetime import timedelta
        if now < exp <= now + timedelta(days=days_ahead):
            alerts.append({
                "offer_id": o.get("id"),
                "role_title": o.get("role_title"),
                "expires_at": exp.isoformat(),
                "hours_remaining": round((exp - now).total_seconds() / 3600, 1),
            })
    return alerts


