# Gap #122: Talent pool rule evaluation
# ---------------------------------------------------------------------------

POOL_RULE_TYPES = frozenset({
    "min_capability_level", "has_credential", "min_endorsements",
    "min_evidence_count", "capability_category", "availability_status",
})


def evaluate_pool_rule(rule: dict, candidate: dict) -> bool:
    """Evaluate a single pool rule against candidate data."""
    rt = rule.get("rule_type", "")
    value = rule.get("value")
    field = rule.get("field", rt)
    candidate_val = candidate.get(field)

    if rt == "min_capability_level":
        return (candidate_val or 0) >= (value or 0)
    if rt == "has_credential":
        creds = candidate.get("credential_types", [])
        return value in creds
    if rt == "min_endorsements":
        return (candidate_val or 0) >= (value or 0)
    if rt == "min_evidence_count":
        return (candidate_val or 0) >= (value or 0)
    if rt == "availability_status":
        return candidate.get("availability_status") == value
    return False


def evaluate_pool_rules(rules: list[dict], candidate: dict) -> dict:
    """Evaluate all pool rules. Returns {eligible, matched, total}."""
    if not rules:
        return {"eligible": True, "matched": 0, "total": 0}
    matched = sum(1 for r in rules if evaluate_pool_rule(r, candidate))
    return {"eligible": matched == len(rules), "matched": matched, "total": len(rules)}


