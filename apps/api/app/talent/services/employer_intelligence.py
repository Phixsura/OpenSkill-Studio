@dataclass(frozen=True, slots=True)
class ComplianceReport:
    report_type: str
    period_start: str
    period_end: str
    total_applications: int
    applications_by_source: dict[str, int]
    applications_by_stage: dict[str, int]
    offer_rate: float
    hire_rate: float
    adverse_impact_flags: list[str]


def compute_adverse_impact(
    group_a_selected: int, group_a_total: int,
    group_b_selected: int, group_b_total: int,
) -> dict:
    """Compute adverse impact ratio (four-fifths rule).

    If selection rate for any group < 80% of highest group → adverse impact.
    """
    rate_a = group_a_selected / group_a_total if group_a_total > 0 else 0
    rate_b = group_b_selected / group_b_total if group_b_total > 0 else 0

    if rate_a == 0 and rate_b == 0:
        return {"ratio": 1.0, "adverse_impact": False, "note": "No selections"}

    higher = max(rate_a, rate_b)
    lower = min(rate_a, rate_b)
    ratio = lower / higher if higher > 0 else 0

    return {
        "ratio": round(ratio, 3),
        "adverse_impact": ratio < 0.8,
        "threshold": 0.8,
        "rate_a": round(rate_a, 3),
        "rate_b": round(rate_b, 3),
    }


