# ---------------------------------------------------------------------------

@dataclass(frozen=True, slots=True)
class Department:
    id: str
    org_id: str
    name: str
    parent_department_id: str | None
    head_user_id: str | None
    member_count: int


def build_department_tree(departments: list[dict]) -> list[dict]:
    """Build hierarchical department tree from flat list."""
    by_id = {d["id"]: {**d, "children": []} for d in departments}
    roots = []
    for d in by_id.values():
        parent = d.get("parent_department_id")
        if parent and parent in by_id:
            by_id[parent]["children"].append(d)
        else:
            roots.append(d)
    return roots


