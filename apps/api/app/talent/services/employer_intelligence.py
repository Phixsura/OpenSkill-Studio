# ---------------------------------------------------------------------------

def compute_brand_health_trend(snapshots: list[dict]) -> dict:
    """Compute employer brand health trend over time."""
    if not snapshots:
        return {"trend": "insufficient_data", "snapshots": []}

    scores = [s.get("reputation_score", 0) for s in snapshots]
    if len(scores) < 2:
        return {"trend": "insufficient_data", "current": scores[0] if scores else 0, "snapshots": snapshots}

    recent = scores[-1]
    previous = scores[-2]
    delta = recent - previous

    if delta > 5:
        trend = "improving"
    elif delta < -5:
        trend = "declining"
    else:
        trend = "stable"

    return {
        "trend": trend,
        "current": recent,
        "previous": previous,
        "delta": round(delta, 1),
        "snapshots": snapshots,
    }
