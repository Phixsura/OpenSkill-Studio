def generate_offer_html(offer: dict) -> str:
    """Generate print-ready HTML for an offer letter."""
    from html import escape
    title = escape(str(offer.get("role_title", "")))
    comp = escape(str(offer.get("compensation_text", "Competitive")))
    start = offer.get("start_date", "TBD")
    conditions = offer.get("conditions", [])
    cond_items = "".join(f"<li>{escape(str(c))}</li>" for c in conditions)

    return f"""<!DOCTYPE html><html><head><meta charset="utf-8">
<title>Offer Letter — {title}</title>
<style>body{{font-family:system-ui;max-width:700px;margin:40px auto;padding:0 20px}}
h1{{border-bottom:2px solid #3b82f6;padding-bottom:8px}} .meta{{color:#6b7280;font-size:14px}}</style>
</head><body><h1>Offer of Employment</h1>
<p><strong>Position:</strong> {title}</p>
<p><strong>Compensation:</strong> {comp}</p>
<p><strong>Start Date:</strong> {escape(str(start))}</p>
{"<h3>Conditions</h3><ul>" + cond_items + "</ul>" if conditions else ""}
<p class="meta">Generated by OpenSkill Studio — {datetime.now(UTC).strftime('%Y-%m-%d')}</p>
</body></html>"""


