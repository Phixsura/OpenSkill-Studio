# Gap #126: Candidate relationship timeline
# ---------------------------------------------------------------------------

def build_relationship_timeline(events: list[dict]) -> list[dict]:
    """Build a unified timeline of all interactions with a candidate.

    Merges: applications, messages, interviews, outreach, notes.
    """
    timeline = []
    for ev in events:
        timeline.append({
            "type": ev.get("type", "unknown"),
            "timestamp": ev.get("timestamp"),
            "summary": ev.get("summary", ""),
            "actor": ev.get("actor"),
            "details": ev.get("details"),
        })
    timeline.sort(key=lambda e: e.get("timestamp", ""))
    return timeline


